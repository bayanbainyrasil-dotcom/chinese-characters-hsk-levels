export function hintStageOf(pending) {
  if(!pending)return 0;
  return Number.isInteger(pending.hintStage)?Math.max(0,Math.min(3,pending.hintStage)):(pending.assisted?3:0);
}
export function maskTarget(text,char){return String(text??'').split(char).join('□');}
export function mnemonicFor(char){const entry=MNEMONICS[char];return entry?{...entry,ids:IDS[char]}:null;}
export function validateNotes(notes={}) {
  if(!notes||typeof notes!=='object'||Array.isArray(notes)||Object.keys(notes).length>1200)throw new Error('Неверный формат личных ассоциаций');
  for(const [char,note] of Object.entries(notes)){
    if(!/^[\u3400-\u4dbf\u4e00-\u9fff]$/.test(char)||typeof note!=='string'||note.length>500)throw new Error('Ассоциация: один иероглиф и не более 500 символов');
  }
  return Object.fromEntries(Object.entries(notes).filter(([,text])=>text.trim()));
}
